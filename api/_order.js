// Shared helpers for the order endpoints: customer validation and the order email text.

const clip = (v, n) => String(v ?? '').replace(/[\u0000-\u001f\u007f]/g, ' ').trim().slice(0, n);

const emailOk = (v) => /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(v);
const phoneOk = (v) => {
  const d = String(v).replace(/[\s-]/g, '');
  return /^(\+?91)?[6-9]\d{9}$/.test(d) || /^\+?\d{8,15}$/.test(d);
};

/** Returns { ok: true, customer, shipping, notes } with trimmed values, or { ok: false, message }. */
export function validateCustomer(b) {
  const c = b?.customer || {};
  const s = b?.shipping || {};
  const customer = { name: clip(c.name, 100), email: clip(c.email, 120), phone: clip(c.phone, 20) };
  const shipping = {
    address: clip(s.address, 250),
    city: clip(s.city, 60),
    state: clip(s.state, 60),
    pin: clip(s.pin, 6),
  };
  if (customer.name.length < 2) return { ok: false, message: 'Please enter your full name.' };
  if (!emailOk(customer.email)) return { ok: false, message: 'Please enter a valid email address.' };
  if (!phoneOk(customer.phone)) return { ok: false, message: 'Please enter a valid phone number.' };
  if (shipping.address.length < 6) return { ok: false, message: 'Please enter your street address.' };
  if (shipping.city.length < 2) return { ok: false, message: 'Please enter your city.' };
  if (shipping.state.length < 2) return { ok: false, message: 'Please enter your state.' };
  if (!/^\d{6}$/.test(shipping.pin)) return { ok: false, message: 'A valid 6-digit PIN code is required.' };
  return { ok: true, customer, shipping, notes: clip(b?.notes, 1000) };
}

/** Order references are generated by the browser; accept only a safe shape. */
export function cleanRef(v) {
  const ref = String(v || '').trim();
  return /^BLY-[A-Z0-9]{4,20}$/.test(ref) ? ref : '';
}

export function buildOrderText({ ref, payment, extra = '', priced, customer, shipping, notes, delhiveryLine }) {
  const lines = priced.lines
    .map((l) => `- ${l.name} (${l.variant}) x ${l.qty} @ INR ${l.unitPrice} = INR ${l.lineTotal}`)
    .join('\n');
  return `Order ${ref}
Payment: ${payment}
${extra ? extra + '\n' : ''}
${lines}

Subtotal: INR ${priced.subtotal}
Shipping: ${priced.ship.free ? 'FREE' : 'INR ' + priced.ship.amount} (${priced.ship.zone === 'jk' ? 'Jammu & Kashmir' : 'Pan-India'})
Total: INR ${priced.total}

${delhiveryLine}

Customer: ${customer.name} | ${customer.email} | ${customer.phone}
Ship to: ${shipping.address}, ${shipping.city}, ${shipping.state} ${shipping.pin}
Notes: ${notes}`;
}
